    def __init__(self, lang="en"):
        self.set_language(lang)

    def set_language(self, lang):
        self.lang = lang if lang in STRINGS else "en"

    def get(self, key, **kwargs):
        value = STRINGS[self.lang].get(key)
        if value is None:
            value = key
        return value.format(**kwargs)


